// Generates supabase/seed.sql from scripts/seed-data.mjs. Deterministic UUIDs + ON CONFLICT DO NOTHING make the
// seed safe to re-run: it never overwrites what the owner edited from the admin.  Run: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as d from './seed-data.ts'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const q = (s) => `'${String(s).replaceAll("'", "''")}'`
const arr = (xs, type) => (xs.length === 0 ? `'{}'::${type}[]` : `array[${xs.map(q).join(', ')}]::${type}[]`)
const id = (prefix, n) => `${prefix}0000000-0000-4000-8000-${String(n).padStart(12, '0')}`

const catId = Object.fromEntries(d.categories.map((c, i) => [c.key, id('c', i + 1)]))
const groupId = Object.fromEntries(d.groups.map((g, i) => [g.key, id('b', i + 1)]))
const productId = Object.fromEntries(d.products.map((p, i) => [p.name, id('a', i + 1)]))

const out = []
const push = (s = '') => out.push(s)

push(
  '-- Takitho · seed. GENERATED by scripts/gen-seed.mjs from scripts/seed-data.mjs — edit the data file, not this one.',
)
push(
  '-- Safe to re-run (deterministic ids + ON CONFLICT DO NOTHING). Prices are EXAMPLES; real data is [COMPLETAR].',
)
push()

push('-- Store: [COMPLETAR] address, WhatsApp, social networks and transfer data are filled from the admin.')
push(`update public.store_settings set public_url = '' where id = 1;`)
push()

push('insert into public.categories (id, name, slug, description, sort) values')
push(
  d.categories
    .map((c, i) => `  (${q(catId[c.key])}, ${q(c.name)}, ${q(c.key)}, ${q(c.description)}, ${i + 1})`)
    .join(',\n'),
)
push('on conflict (id) do nothing;')
push()

push('insert into public.modifier_groups (id, name, min_select, max_select, is_required, sort) values')
push(
  d.groups
    .map((g, i) => `  (${q(groupId[g.key])}, ${q(g.name)}, ${g.min}, ${g.max}, ${g.required}, ${i + 1})`)
    .join(',\n'),
)
push('on conflict (id) do nothing;')
push()

push('insert into public.modifiers (id, group_id, name, price_delta, sort) values')
let m = 0
const modRows = []
for (const g of d.groups) {
  g.options.forEach(([name, delta], j) => {
    m++
    modRows.push(`  (${q(id('d', m))}, ${q(groupId[g.key])}, ${q(name)}, ${delta}, ${j + 1})`)
  })
}
push(modRows.join(',\n'))
push('on conflict (id) do nothing;')
push()

push(
  'insert into public.products (id, category_id, type, name, slug, description, unit_label, price, image_public_id, spicy_level, tags, sort) values',
)
push(
  d.products
    .map((p, i) => {
      const slug = p.name
        .normalize('NFD')
        .replace(/[̀-ͯ]/g, '')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '')
      return `  (${q(productId[p.name])}, ${q(catId[p.cat])}, ${q(p.type ?? 'single')}, ${q(p.name)}, ${q(slug)}, ${q(p.desc)}, ${q(p.unit)}, ${p.price}, ${q(`${d.CLOUDINARY_FOLDER}/${p.image}`)}, ${p.spicy}, ${arr(p.tags, 'text')}, ${i + 1})`
    })
    .join(',\n'),
)
push('on conflict (id) do nothing;')
push()

push('insert into public.product_modifier_groups (product_id, group_id, sort) values')
const links = d.products.flatMap((p) =>
  p.groups.map((g, j) => `  (${q(productId[p.name])}, ${q(groupId[g])}, ${j + 1})`),
)
push(links.join(',\n'))
push('on conflict do nothing;')
push()

const comboRows = d.products.flatMap((p) =>
  (p.combo ?? []).map(([name, qty]) => `  (${q(productId[p.name])}, ${q(productId[name])}, ${qty})`),
)
push('insert into public.combo_items (combo_id, product_id, quantity) values')
push(comboRows.join(',\n'))
push('on conflict do nothing;')
push()

push('-- [COMPLETAR] opening hours (example shifts; Fri/Sat cross midnight until 02:00)')
push('insert into public.opening_hours (weekday, opens_at, closes_at) values')
push(d.openingHours.map(([w, o, c]) => `  (${w}, ${q(o)}, ${q(c)})`).join(',\n'))
push('on conflict do nothing;')
push()

push('-- [COMPLETAR] delivery zones')
push('insert into public.delivery_zones (id, name, neighborhoods, fee, min_order, sort) values')
push(
  d.zones
    .map(
      (z, i) =>
        `  (${q(id('e', i + 1))}, ${q(z.name)}, ${arr(z.neighborhoods, 'text')}, ${z.fee}, ${z.minOrder}, ${i + 1})`,
    )
    .join(',\n'),
)
push('on conflict (id) do nothing;')
push()

push('insert into public.tables (id, number, label) values')
push(d.tables.map((n, i) => `  (${q(id('f', i + 1))}, ${n}, ${q(`Mesa ${n}`)})`).join(',\n'))
push('on conflict do nothing;')
push()

push(
  'insert into public.coupons (id, code, label, kind, value, scope, scope_ids, weekdays, max_uses_per_phone, auto_apply) values',
)
push(
  d.coupons
    .map((c, i) => {
      const scopeIds = c.scopeCat ? [catId[c.scopeCat]] : []
      const weekdays =
        c.weekdays.length === 0 ? `'{}'::smallint[]` : `array[${c.weekdays.join(', ')}]::smallint[]`
      return `  (${q(id('9', i + 1))}, ${c.code === null ? 'null' : q(c.code)}, ${q(c.label)}, ${q(c.kind)}, ${c.value}, ${q(c.scope)}, ${arr(scopeIds, 'uuid')}, ${weekdays}, ${c.maxPerPhone ?? 'null'}, ${c.autoApply})`
    })
    .join(',\n'),
)
push('on conflict (id) do nothing;')

writeFileSync(path.join(ROOT, 'supabase', 'seed.sql'), out.join('\n') + '\n')
console.log(`seed.sql: ${d.products.length} products, ${d.groups.length} modifier groups, ${m} modifiers`)
